#   เพื่อผลักกล่องที่ไหลมาบนสายพานให้ไปเข้าช่องที่ถูกต้อง แผ่นเอียงมุมไหน
#   ขึ้นกับว่ากล่องต้องไปช่องไหน — ผิวไม่ตั้งฉาก ผลการสะท้อนจึงต่างกันหมด
