#
#   2. แก้ SLOPE จาก [0.0, 1.0] เป็น [0.0, 0.4] — ผิวเอียงน้อยลง และแรงดันลูก
#      จะลดลงตามกันเอง เพราะแรงดันคำนวณจาก "ความชัน" ของรูปทรงโดยตรง
#      ไม่ได้เขียนมือแยกไว้ รูปกับพฤติกรรมจึงขัดกันเองไม่ได้
#
#   3. เพิ่มจุดให้ CONVEX จาก 7 เป็น 13 จุด (ใส่ค่ากลางระหว่างของเดิม)
#      ผิวจะโค้งเนียนขึ้น — จุดยิ่งมากยิ่งใกล้เส้นโค้งจริง นี่คือ piecewise approximation
#
#   4. ลด PLATE_OUT เหลือ 10 แล้วดู: ผิวเกือบตั้งฉาก พฤติกรรมเข้าใกล้ FLAT
