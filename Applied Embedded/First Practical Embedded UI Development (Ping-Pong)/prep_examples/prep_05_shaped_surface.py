# ผิวเอียงต่างออกไป: ลูกที่พุ่งมาแนวนอนชนผิวเอียง จะถูกดันเฉียงขึ้นหรือลงด้วย
#   และตัวที่กำหนดว่าดันแรงแค่ไหนคือ **ความชันของผิวตรงจุดที่โดน**
