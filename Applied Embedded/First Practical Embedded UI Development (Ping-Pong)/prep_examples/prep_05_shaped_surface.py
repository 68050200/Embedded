# ทำไมวิธีนี้ถึงเป็นวิธีของ "วิศวกรรมสมองกลฝังตัว" จริง ๆ:
#
#   การสะท้อนบนผิวมุมใดก็ได้ให้ถูกต้องตามฟิสิกส์ต้องใช้สูตร  v' = v - 2(v·n)n
#   ซึ่งต้องมี dot product, normal vector ที่ normalize แล้ว และรากที่สอง
#   บน MCU ที่ไม่มีหน่วยประมวลผลทศนิยม การคำนวณนั้นกินเวลาหลายร้อยรอบสัญญาณนาฬิกา
#   ต่อการชนหนึ่งครั้ง
#
#   วิธีในไฟล์นี้ใช้แค่ "ลบสองครั้ง + หารหนึ่งครั้ง" หาความชัน แล้วบวกเข้าความเร็ว
#   ไม่กี่รอบเท่านั้น และให้ผลที่ผู้เล่นแยกไม่ออกจากของจริง
#
#   ทักษะนี้ใช้ที่ไหนได้อีก: ตารางเทียบค่าเซนเซอร์ที่ไม่เป็นเส้นตรง (thermistor, load cell),
#     กราฟความสว่างหน้าจอ, เส้นโค้งการเร่งของมอเตอร์, การชดเชยค่าแบตเตอรี่
#     — ทุกครั้งที่เห็น "ตารางค่าคงที่" ในเฟิร์มแวร์ มักเป็นเรื่องเดียวกันนี้
