# (ui เป็นโมดูลเดียวกับที่ bentogame เรียกใช้อยู่ข้างใน จึงใช้ร่วมกันได้)
#
# ไฟล์นี้ไม่ได้ใช้ในข้อสอบ — มีไว้ให้เห็นว่า reflect ไปได้ไกลแค่ไหน

import bentogame as game
import ui

BALL = 14

# ---------------------------------------------------------------- รูปทรงผิว
# แต่ละผิวเขียนเป็น "ระยะยื่นออกมาหาลูก" ไล่จากบนลงล่าง หน่วยเป็นสัดส่วน 0..1
# (0 = ไม่ยื่นเลย, 1 = ยื่นสุด) จำนวนจุดไม่ต้องเท่ากัน — จุดน้อย = หักมุมคม
# จุดมาก = โค้งเนียน โค้ดลากเส้นตรงเชื่อมจุดพวกนี้ให้เอง ไม่ต้องใช้ตรีโกณเลย
SURFACES = [
    ("FLAT (ตั้งฉาก)",  [0.0, 0.0]),
    ("SLOPE (เอียง)",   [0.0, 1.0]),                                # เส้นตรงเอียงล้วน
    ("CONVEX (นูน)",    [0.0, 0.55, 0.87, 1.0, 0.87, 0.55, 0.0]),   # ส่วนโค้งนูน
    ("CONCAVE (เว้า)",  [1.0, 0.55, 0.13, 0.0, 0.13, 0.55, 1.0]),   # ส่วนโค้งเว้า
    ("WEDGE (ลิ่ม)",    [0.0, 1.0, 0.0]),                           # สองหน้าชนกันเป็นปลายแหลม
]

# ผิวต้องเตี้ยพอที่จะเลื่อนได้ทั้งจอจริง ๆ — ผิวสูง 250 บนจอ 398 เลื่อนได้แค่ 148 px
# เตี้ยลงเหลือ 150 จึงเลื่อนได้ 248 px คือเกือบทั้งความสูงจอ
PLATE_H = 150                        # ความสูงของผิว
PLATE_OUT = 70                       # ยื่นออกมาได้ไกลสุดกี่ px
PLATE_RIGHT = game.WIDTH - 90        # ขอบขวาของผิว — เว้นช่องว่างไว้ทางขวา
LINE_W = 6                           # ความหนาเส้น

# เลื่อนได้ตั้งแต่ชิดขอบบนถึงชิดขอบล่าง (ผิวอยู่ขวาจอ ไม่ทับแถบข้อความที่อยู่ซ้าย)
PLATE_MIN_Y = 0
PLATE_MAX_Y = game.HEIGHT - PLATE_H
PLATE_SPEED = 6

# หน้า Playground วาดแถบข้อความของตัวเองทับจอราว 26 px ล่างสุด
# ให้ลูกเด้งเหนือแถบนั้น ไม่งั้นลูกจะหายเข้าไปอยู่หลังแถบเป็นช่วง ๆ เหมือนหลุดจอ
PLAY_BOTTOM = game.HEIGHT - 26

game.title("DEFLECTOR")

ball = game.Box(60, game.HEIGHT // 2, BALL, BALL, game.CYAN)
status = game.Text("", 24, 12, game.WHITE)
counter = game.Text("", 24, 44, game.GB_LIGHT)
game.Text("ขึ้น/ลง = เลื่อน | Z = สลับทรง | Enter = ออก", 24, 76, game.CYAN)

surface_index = 1                    # เริ่มที่ SLOPE (ผิวเอียง)
plate_y = 130.0
# เริ่มให้ชนผิวได้ตั้งแต่ลูกแรก: ระยะจากจุดปล่อยถึงผิวราว 570 px
# ที่ vx=6 ลูกใช้ ~95 เฟรม ถ้า vy=1.2 จะตกลง 114 px ซึ่งเกินความสูงผิว (150) ไปแล้ว
# ลด vy ลงเหลือ 0.6 -> ตกลงแค่ ~57 px ยังอยู่ในระยะผิวพอดี
ball_x, ball_y = 60.0, plate_y + 40
ball_vx, ball_vy = 6.0, 0.6
hits = 0
prev_a = True
line = None                          # ui.Line ตัวปัจจุบัน


def profile_at(t):
    """ระยะยื่น (0..1) ของผิวที่ความสูง t (0 = บนสุด, 1 = ล่างสุด)

    ลากเส้นตรงระหว่างจุดควบคุมสองจุดที่ขนาบ t อยู่ — piecewise linear
    ฟังก์ชันเดียวนี้ใช้ทั้ง "วาดผิว" และ "ตรวจการชน" รูปกับพฤติกรรมจึงตรงกันเสมอ
    """
    pts = SURFACES[surface_index][1]
    span = len(pts) - 1
    if t <= 0:
        return pts[0]
    if t >= 1:
        return pts[span]
    pos = t * span
    k = int(pos)
    return pts[k] + (pts[k + 1] - pts[k]) * (pos - k)


def surface_x(y):
    """ขอบซ้ายของผิว ณ ความสูง y บนจอ — ลูกจะชนที่เส้นนี้"""
    return PLATE_RIGHT - profile_at((y - plate_y) / PLATE_H) * PLATE_OUT


def surface_slope(y):
    """ความชันของผิวตรงจุดนั้น — ตัวที่กำหนดว่าจะดันลูกขึ้นหรือลงแรงแค่ไหน

    วัดจากผลต่างของขอบผิวระหว่างสองจุดที่ห่างกันเล็กน้อย
    ผิวเอียงทางหนึ่ง = ดันลูกทางหนึ่ง · ผิวตั้งฉาก = ไม่ดันเลย
    """
    d = 12.0
    return (surface_x(y + d) - surface_x(y - d)) / (2 * d)


def draw_surface():
    """วาดผิวใหม่ด้วยเส้นเดียว — จุดของเส้นนับจากมุมซ้ายบนของตัว widget เอง"""
    global line
    if line is not None:
        line.delete()
    pts = SURFACES[surface_index][1]
    line = ui.Line(x=int(PLATE_RIGHT - PLATE_OUT), y=int(plate_y),
                   w=PLATE_OUT + 8, h=PLATE_H + 8,
                   color=game.GB_LIGHTEST, value=LINE_W)
    last = len(pts) - 1
    for i, p in enumerate(pts):
        line.add_point(int(PLATE_OUT - p * PLATE_OUT),   # ยื่นมาก = อยู่ซ้ายมาก
                       int(i * PLATE_H / last))


def show_readout():
    name, pts = SURFACES[surface_index]
    counter.set("%s | %d จุด | เด้งแล้ว %d ครั้ง" % (name, len(pts), hits))


def show_surface():
    status.set("SURFACE: %s" % SURFACES[surface_index][0])
    show_readout()
    draw_surface()


show_surface()

# ============================================================================
# แยกเป็นฟังก์ชันย่อยตามลำดับของระบบสมองกลฝังตัว: รับรู้ -> ตัดสินใจ -> สั่งการ
# ทุกไฟล์ในชุดนี้ใช้โครงเดียวกัน อ่านไฟล์หนึ่งเป็น อ่านที่เหลือออกหมด
# ============================================================================


def handle_shape_button(keys):
    """ปุ่ม Z เปลี่ยนรูปทรงผิว — กดหนึ่งครั้งเปลี่ยนหนึ่งทรง (debounce)"""
    global surface_index, prev_a

    if keys.a and not prev_a:
        surface_index = (surface_index + 1) % len(SURFACES)
        show_surface()
    prev_a = keys.a


def move_surface(keys):
    """ผู้เล่นเลื่อนผิวขึ้น/ลง — ย้ายทั้งเส้นด้วยคำสั่งเดียว"""
    global plate_y

    if keys.up or keys.down:
        plate_y += (-PLATE_SPEED if keys.up else PLATE_SPEED)
        plate_y = max(PLATE_MIN_Y, min(PLATE_MAX_Y, plate_y))       # clamp
        line.pos(int(PLATE_RIGHT - PLATE_OUT), int(plate_y))


def move_ball():
    """integrate + สะท้อนขอบจอทั้งสี่ด้าน (เหมือนคาบ 5) — ลูกจึงเด้งไม่มีวันจบ"""
    global ball_x, ball_y, ball_vx, ball_vy

    ball_x += ball_vx
    ball_y += ball_vy

    if ball_y <= 0:
        ball_y = 0                                 # ดันกลับเข้าขอบก่อน
        ball_vy = -ball_vy                         # แล้วค่อยกลับทิศ
        game.sfx("wall")
    elif ball_y >= PLAY_BOTTOM - BALL:
        ball_y = PLAY_BOTTOM - BALL
        ball_vy = -ball_vy
        game.sfx("wall")
    if ball_x <= 0:
        ball_x = 0
        ball_vx = -ball_vx
        game.sfx("wall")
    elif ball_x >= game.WIDTH - BALL:
        # ต้องมีขอบขวาด้วย ไม่งั้นเวลาลูกพลาดผิว (เช่นเลื่อนผิวหนีไปแล้ว)
        # ลูกจะวิ่งออกนอกจอแล้วหายไปเลย ไม่กลับมาอีก
        ball_x = game.WIDTH - BALL
        ball_vx = -ball_vx
        game.sfx("wall")


def bounce_off_surface():
    """หัวใจของตัวอย่างนี้: ชนผิวเอียงแล้วถูกดันตามความชันของผิวตรงจุดที่โดน"""
    global ball_x, ball_vx, ball_vy, hits

    cy = ball_y + BALL / 2
    if ball_vx > 0 and plate_y <= cy <= plate_y + PLATE_H:
        edge = surface_x(cy)                       # ขอบผิว ณ ความสูงของลูก
        if ball_x + BALL >= edge:
            ball_x = edge - BALL                   # ดันกลับมาที่ผิวก่อน
            ball_vx = -ball_vx                     # แล้วค่อยกลับทิศ (เหมือนคาบ 5)

            # ส่วนที่ "ผิวเอียง" เพิ่มเข้ามา: ยิ่งผิวชันมาก ยิ่งดันแรง
            ball_vy += surface_slope(cy) * 7.0
            ball_vy = max(-11.0, min(11.0, ball_vy))   # clamp เหมือนคาบ 6

            hits += 1
            show_readout()
            game.sfx("paddle")


def on_each_frame():
    """หนึ่งเฟรม = อ่านปุ่ม -> เลื่อนผิว -> ขยับลูก -> ตรวจการชน -> วาด"""
    keys = game.keys()
    if keys.start:
        return False

    handle_shape_button(keys)
    move_surface(keys)
    move_ball()
    bounce_off_surface()
    ball.move_to(ball_x, ball_y)


game.run(on_each_frame, fps=30)

