# prep_01_radar_beam.py — เตรียมสอบกลางภาค ตัวอย่างที่ 1
#
# ทักษะที่ทบทวน: integrate + reflect (คาบ 5) + ขอบเขตที่ "ขยับได้"
#
# เรื่องราว: เรดาร์ตรวจการณ์กวาดลำแสงกลับไปมาในช่วงที่ผู้ควบคุมตั้งไว้ (sector scan)
#   ระหว่างทำงาน ผู้ควบคุมบีบช่วงกวาดให้แคบลงได้ เพื่อโฟกัสเฉพาะบริเวณที่สนใจ
#   — เรดาร์เดินเรือทำแบบนี้จริง และเครื่องจักร CNC ก็มี "soft limit" แบบเดียวกัน
#
# ================== ทำไมตัวอย่างนี้ถึงมีอยู่ ==================
#
# คาบ 5 สอนลูกบอลเด้งกำแพงไปแล้ว ตัวอย่างนี้จึง **ไม่ได้สอนการเด้งซ้ำ**
# แต่สอนสิ่งที่คาบ 5 ไม่มี: **ขอบเขตที่เปลี่ยนค่าได้ระหว่างโปรแกรมกำลังทำงาน**
#
# กำแพงใน Pong อยู่กับที่ตลอดเกม ลูกบอลจึงทะลุออกไปได้ไม่เกินหนึ่งก้าว
# แต่พอขอบเขตขยับเข้าหาวัตถุได้ วัตถุจะพบว่าตัวเอง **อยู่นอกเขตไปไกลกว่าหนึ่งก้าว**
# ซึ่งเป็นสถานการณ์ที่โค้ดแบบ Pong รับมือไม่ได้
#
# ข้อสอบใช้เรื่องนี้: โซนอันตรายที่เลื่อนขึ้นลงในช่วงที่กำหนด คือโครงเดียวกันนี้
#
# หัวใจที่ต้องจำให้ได้:
#   1. ตำแหน่งกับความเร็วเป็นคนละตัวแปร   beam_x  กับ  beam_vx
#   2. integrate = บวกความเร็วเข้าตำแหน่งทุกเฟรม      beam_x += beam_vx
#   3. reflect   = กลับเครื่องหมายเมื่อชนขอบ           beam_vx = -beam_vx
#   4. **ดันกลับเข้าขอบก่อนกลับเครื่องหมายเสมอ** — ข้อนี้จะไม่มีความหมายเลย
#      ถ้าขอบอยู่กับที่ แต่จะเป็นเรื่องเป็นราวทันทีเมื่อขอบขยับได้
#
# วิธีเล่น: ลูกศรซ้าย = บีบช่วงให้แคบ · ลูกศรขวา = ขยายช่วง · Enter = ออก

import bentogame as game

BEAM_W, BEAM_H = 10, 150
SECTOR_Y = 150
SECTOR_MIN_W = 70                  # แคบสุดที่ผู้ควบคุมบีบได้
WALL_SPEED = 3.0                   # ผนังแต่ละข้างขยับเร็วแค่ไหนต่อเฟรม

game.title("RADAR SECTOR")

# --- ช่วงกวาด: กล่องที่ขอบซ้าย/ขวาของมันคือขอบที่ลำแสงต้องสะท้อน ---
sector = game.Box(140, SECTOR_Y, 510, BEAM_H, game.BLACK,
                  border=game.GB_LIGHT, border_w=2)
# สีขอบถูกล็อกตั้งแต่ตอนสร้าง (set_color เปลี่ยนแค่สีพื้น) จึงตั้งขอบเป็นสีดำ
# ไม่งั้นตอนลำแสงเปลี่ยนเป็นสีแดง จะยังมีเส้นขอบสีฟ้าค้างอยู่
beam = game.Box(300, SECTOR_Y, BEAM_W, BEAM_H, game.CYAN,
                border=game.BLACK, border_w=0)

status = game.Text("", 24, 12, game.WHITE)
counter = game.Text("", 24, 44, game.GB_LIGHT)
game.Text("ซ้าย = บีบแคบ | ขวา = ขยาย | Enter = ออก", 24, 76, game.CYAN)

# --- สถานะทั้งหมด: 4 ตัวเลขนี้อธิบายระบบได้ครบ ---
beam_x = 300.0
beam_vx = 4.5
lo = 140.0                         # ขอบซ้ายของช่วงกวาด
hi = 650.0                         # ขอบขวาของช่วงกวาด
bounces = 0


def adjust_sector(keys):
    """ผู้ควบคุมบีบ/ขยายช่วงกวาดระหว่างที่เรดาร์ยังทำงานอยู่"""
    global lo, hi

    if keys.left:                              # บีบเข้าหากันทั้งสองข้าง
        lo += WALL_SPEED
        hi -= WALL_SPEED
    if keys.right:
        lo -= WALL_SPEED
        hi += WALL_SPEED
    lo = max(40.0, lo)                         # ไม่ให้ทะลุจอ
    hi = min(game.WIDTH - 40.0, hi)
    if hi - lo < SECTOR_MIN_W:                 # ไม่ให้แคบจนไม่เหลือช่วง
        mid = (lo + hi) / 2
        lo, hi = mid - SECTOR_MIN_W / 2, mid + SECTOR_MIN_W / 2
    sector.move_to(lo, SECTOR_Y)
    sector.resize(int(hi - lo), BEAM_H)


def sweep_beam():
    """หัวใจของตัวอย่างนี้: integrate + reflect ที่ขอบซึ่ง 'ขยับได้'"""
    global beam_x, beam_vx, bounces

    # --- STEP 1: integrate — เดินหน้าทีละก้าวตามความเร็ว ---
    beam_x += beam_vx

    # --- STEP 2: reflect ที่ขอบซ้าย ---
    # ลำดับสำคัญมาก: ดันกลับเข้าขอบ "ก่อน" แล้วค่อยกลับเครื่องหมาย
    if beam_x < lo:
        beam_x = lo                            # <<< บรรทัดที่แบบฝึกข้อ 2 ให้ลบ
        beam_vx = -beam_vx
        bounces += 1
        game.sfx("wall")

    # --- STEP 3: reflect ที่ขอบขวา (ตรรกะเดียวกันทุกประการ) ---
    elif beam_x > hi - BEAM_W:
        beam_x = hi - BEAM_W                   # <<< และบรรทัดนี้
        beam_vx = -beam_vx
        bounces += 1
        game.sfx("wall")

    # --- STEP 4: วาดผลลัพธ์ ---
    beam.move_to(beam_x, SECTOR_Y)


def draw_hud():
    """แสดงผล — ลำแสงเปลี่ยนเป็นสีแดงทันทีที่หลุดออกนอกช่วงกวาด"""
    outside = beam_x < lo - 1 or beam_x > hi - BEAM_W + 1
    beam.set_color(game.RED if outside else game.CYAN)
    if outside:
        status.set("*** ลำแสงหลุดออกนอกช่วงกวาด ***")
    else:
        status.set("ตำแหน่ง %d   ความเร็ว %+.1f" % (beam_x, beam_vx))
    counter.set("ช่วงกวาด %d-%d (กว้าง %d) | สะท้อน %d ครั้ง"
                % (lo, hi, hi - lo, bounces))


def on_each_frame():
    keys = game.keys()
    if keys.start:
        return False

    adjust_sector(keys)
    sweep_beam()
    draw_hud()


game.run(on_each_frame, fps=30)

