# ลองเล่นกับมันดู (ทำให้เข้าใจจริง ไม่ใช่แค่อ่านผ่าน):
#
#   1. กดลูกศรซ้ายค้างไว้ บีบช่วงให้แคบที่สุด แล้วดูลำแสงวิ่งถี่ขึ้นเรื่อย ๆ
#      สังเกตว่าไม่ว่าบีบเร็วแค่ไหน ลำแสงก็ยังอยู่ในช่วงเสมอ ไม่เคยเป็นสีแดง
#      — บรรทัด beam_x = lo คือสิ่งเดียวที่ทำให้เป็นแบบนั้น
#
#   2. **ลบ beam_x = lo และ beam_x = hi - BEAM_W ออก (เหลือแค่การกลับเครื่องหมาย)**
#      แล้วรันใหม่ ทำสองอย่างนี้ตามลำดับ:
#
#      ก) อย่าเพิ่งกดอะไร ปล่อยให้ลำแสงวิ่งไปมาเฉย ๆ
#         **จะไม่เห็นอะไรผิดปกติเลย** เพราะลำแสงทะลุออกไปได้ไม่เกินหนึ่งก้าว (4.5 px)
#         แล้วก้าวถัดไปมันก็กลับเข้ามาพอดี — ขอบที่อยู่กับที่ปกปิดบั๊กนี้ไว้สนิท
#
#      ข) ทีนี้กดลูกศรซ้ายค้าง บีบช่วงให้แคบ
#         **ลำแสงจะกลายเป็นสีแดงค้างอยู่นอกช่วง สั่นอยู่กับที่ ออกมาไม่ได้อีกเลย**
#         เพราะผนังเดินผ่านมันไปแล้ว มันจึงอยู่นอกเขตไกลเกินหนึ่งก้าว
#         พอกลับเครื่องหมายทุกเฟรม มันก็สั่นอยู่ตรงนั้นตลอดไป
#
#      นี่คือเหตุผลที่แบบฝึกข้อนี้ต้องมีขอบที่ขยับได้ ถ้าขอบอยู่กับที่แบบ Pong
#      บั๊กนี้จะซ่อนอยู่จนกว่าจะเจอของจริง — ซึ่งของจริงคือเครื่องจักรที่พังไปแล้ว
#
#   3. เปลี่ยน WALL_SPEED เป็น 0.5 แล้วลองข้อ 2 ซ้ำ จะเห็นว่ายังติดเหมือนเดิม
#      ผนังไม่ต้องขยับเร็วเลย ขอแค่ขยับได้ก็พอ
#
#   4. เปลี่ยน beam_vx เริ่มต้นเป็น 20.0 แล้วดูว่าลำแสงยังอยู่ในช่วงไหม
#      (ยังอยู่ — เพราะการดันกลับเข้าขอบไม่สนใจว่าความเร็วเท่าไร)
#
# ทักษะนี้ใช้ที่ไหนได้อีก: soft limit ของแกน CNC, ช่วงหมุนของกล้องวงจรปิดที่ตั้งค่าได้,
#   ลิมิตของแขนกลที่ปรับตามชิ้นงาน, ช่วงความถี่ที่เครื่องสแกนกวาด
#   — ทั้งหมดคือ "ขอบเขตที่โปรแกรมเปลี่ยนได้ระหว่างทำงาน" ซึ่งต้องดันค่ากลับเข้าเขตเสมอ
