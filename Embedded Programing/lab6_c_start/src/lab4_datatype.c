#include <stdio.h>
#include <stdint.h>     /* ต้อง include เพื่อใช้ uint8_t, int16_t ฯลฯ */

int main(void) {

    /* ------------------------------------------------------------
       [1] ตัวอย่าง
       ------------------------------------------------------------
       sizeof(ชนิด) บอกว่าชนิดนั้นกินหน่วยความจำกี่ไบต์
       ใช้ %zu ในการพิมพ์ค่าจาก sizeof
    */
    printf("--- [1] ตัวอย่าง: ชนิดพื้นฐานของ C ---\n");

    printf("char   = %zu ไบต์\n", sizeof(char));
    printf("int    = %zu ไบต์   <-- ขนาดไม่แน่นอนข้ามแพลตฟอร์ม!\n", sizeof(int));
    printf("float  = %zu ไบต์\n", sizeof(float));
    printf("double = %zu ไบต์\n", sizeof(double));

    printf("\n--- ชนิดจาก stdint.h ที่งานฝังตัวใช้ ---\n");
    printf("uint8_t  = %zu ไบต์   เก็บ 0 ถึง 255\n", sizeof(uint8_t));
    printf("int8_t   = %zu ไบต์   เก็บ -128 ถึง 127\n", sizeof(int8_t));
    printf("uint32_t = %zu ไบต์\n", sizeof(uint32_t));

    /* ตัวแปรเหล่านี้ระบุขนาดชัดเจน ใช้ได้เหมือนกันทุกแพลตฟอร์ม */
    uint8_t sensor_value = 200;
    int8_t  temperature  = -15;
    printf("\nsensor_value = %u (uint8_t)\n", sensor_value);
    printf("temperature  = %d องศา (int8_t)\n", temperature);


    /* ------------------------------------------------------------
       [2] ลองทำเอง
       ------------------------------------------------------------ */
    printf("\n--- [2] ลองทำเอง ---\n");

    /* TODO 4.1 : พิมพ์ขนาดของ int16_t, uint16_t และ long           */
    printf("TODO 4.1 :\n");
    printf("int16_t  = %zu ไบต์ \n", sizeof(int16_t));
    printf("uint16_t  = %zu ไบต์ \n", sizeof(uint16_t));
    printf("long  = %zu ไบต์ \n", sizeof(long));
    /* TODO 4.2 : ประกาศตัวแปร uint16_t ชื่อ adc_value เก็บค่า 4095
                  (ค่าสูงสุดของ ADC 12 บิต) แล้ว printf ออกมา       */
    printf("TODO 4.2 :\n");
    uint16_t adc_value = 4095;
    printf("adc_value = %u\n", adc_value);

    /* TODO 4.3 : ลองประกาศ uint8_t ชื่อ big = 300; แล้ว printf ดู
                  ค่าที่ได้เป็นเท่าไร ทำไมถึงไม่ใช่ 300              */
   printf("TODO 4.3 :\n");
    uint8_t big = 300;
    printf("big = %u\n", big);


    /* ------------------------------------------------------------
       [3] ท้าทาย
       ------------------------------------------------------------ */
    printf("\n--- [3] ท้าทาย ---\n");

    /* TODO 4.4 : ถ้าต้องเก็บค่าอุณหภูมิ -40 ถึง 125 องศา
                  ควรใช้ชนิดใดจึงประหยัดหน่วยความจำที่สุด
                  เขียนโค้ดประกาศตัวแปรนั้น พร้อมคอมเมนต์อธิบายเหตุผล */
    printf("TODO 4.3 :\n");
    int8_t temp = 125;
    printf("ถ้าต้องเก็บค่าอุณหภูมิ -40 ถึง 125 องศา ควรใช้ชนิดใดจึงประหยัดหน่วยความจำที่สุด เขียนโค้ดประกาศตัวแปรนั้น พร้อมคอมเมนต์อธิบายเหตุผล\n");
    printf("เลือก int8_t เพราะint8_t   = %zu ไบต์   เก็บ -128 ถึง 127\n", sizeof(int8_t));

    return 0;
}
