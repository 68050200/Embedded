/* ============================================================
   LAB 1 : ตัวแปรและการแสดงผล
   วิธีรัน: เลือก env:lab1_variables ที่แถบล่าง -> กด Upload
   ============================================================ */

#include <stdio.h>

int main(void) {

    /* ------------------------------------------------------------
       [1] ตัวอย่าง  -- อ่านให้เข้าใจก่อน แล้วรันดูผล
       ------------------------------------------------------------
       Python : x = 10                 (ไม่ต้องบอกชนิด)
       C      : int x = 10;            (ต้องบอกชนิด และจบด้วย ;)
    */
    printf("--- [1] ตัวอย่าง ---\n");

    int   x = 10;        /* จำนวนเต็ม */
    float y = 3.5;       /* ทศนิยม    */
    char  c = 'A';       /* ตัวอักษร 1 ตัว ใช้ single quote */

    printf("x = %d\n", x);        /* %d คู่กับ int   */
    printf("y = %.2f\n", y);      /* %f คู่กับ float, .2 = ทศนิยม 2 ตำแหน่ง */
    printf("c = %c\n", c);        /* %c คู่กับ char  */

    /* คำนวณแล้วแสดงผลในบรรทัดเดียว */
    printf("x + 5 = %d\n", x + 5);


    /* ------------------------------------------------------------
       [2] ลองทำเอง  -- ลบเครื่องหมาย comment ออกแล้วเติมให้สมบูรณ์
       ------------------------------------------------------------ */
    printf("\n--- [2] ลองทำเอง ---\n");

    /* TODO 1.1 : ประกาศตัวแปร int ชื่อ year เก็บปี พ.ศ. ปัจจุบัน
                  แล้ว printf ออกมาว่า  "ปีนี้ พ.ศ. 2569"           */
    int year = 2569;
    printf("ปีนี้ พ.ศ. %d\n", year);

    /* TODO 1.2 : ประกาศตัวแปร float ชื่อ gpa เก็บเกรดเฉลี่ยของตัวเอง
                  แล้ว printf แสดงทศนิยม 2 ตำแหน่ง                  */

    float gpa = 3.57;
    printf("gpa = %.2f\n", gpa);
    /* TODO 1.3 : ประกาศตัวแปร int สองตัวคือ a = 17 และ b = 5
                  แล้ว printf ผลของ a + b, a - b, a * b, a / b, a % b
                  (สังเกตว่า 17 / 5 ใน C ได้เท่าไร ทำไมถึงไม่ใช่ 3.4)  */
    int a = 17;
    int b = 5;
    printf("a + b = %d\n", a + b);
    printf("a - b = %d\n", a - b);
    printf("a * b = %d\n", a * b);
    printf("a / b = %d\n", a / b);
    printf("a % b = %d\n", a % b);
    /* ------------------------------------------------------------
       [3] ท้าทาย  -- ทำได้เมื่อเสร็จข้อบนแล้ว
       ------------------------------------------------------------ */
    printf("\n--- [3] ท้าทาย ---\n");

    /* TODO 1.4 : ประกาศตัวแปรเก็บชื่อวิชา (char array) แล้วแสดงผลด้วย %s
                  คำใบ้: char subject[] = "Embedded";                */
    char subject[] = "Embedded";
    printf("%s\n", subject);

    return 0;
}
