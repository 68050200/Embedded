/* ---------- ขาที่ใช้ ---------- */
#define LED_BASE    16    /* หลอดดวงล่างสุดอยู่ที่ GPIO16 ดวงถัดไปคือ 17 18 19 */
#define LED_COUNT   4     /* จำนวนหลอดในแถบ  ใส่ 3 ได้ถ้ามีหลอดแค่ 3 ดวง */
#define ALARM_PIN   2     /* LED ที่ติดมากับบอร์ด ใช้เป็นไฟเตือน ไม่ต้องต่อเพิ่ม */

/* ---------- ช่วงค่าที่วัดได้ ---------- */
/* เก็บอุณหภูมิเป็นเลขจุดตรึงแบบ Q8.8  คือ 1 องศา = 256 หน่วย
   ทำแบบนี้เพื่อไม่ต้องใช้ float ซึ่งบน MCU หลายรุ่นไม่มีวงจรคำนวณให้ */
#define Q88(x)      ((int16_t)((x) * 256))
#define TEMP_LO     Q88(20)   /* ต่ำกว่านี้ถือว่าระดับ 0 = ดับหมด  */
#define TEMP_HI     Q88(40)   /* ถึงค่านี้ถือว่าเต็มแถบ = ไฟเตือนติด */

/* ---------- โครงสร้างข้อมูล ---------- */

/* สถานะของระบบ บีบให้เหลือไบต์เดียวด้วย bit-field (ครั้งที่ 7) */
typedef struct {
    uint8_t level : 3;   /* ระดับปัจจุบัน 0 ถึง LED_COUNT      */
    uint8_t alarm : 1;   /* 1 เมื่อเต็มแถบ                     */
    uint8_t mode  : 2;   /* 0 = ปกติ  1 = ทดสอบ  2 = หยุด      */
    uint8_t spare : 2;   /* เผื่อไว้                            */
} SysState;

/* หนึ่งบรรทัดใน log  ออกแบบให้ลงตัวพอดี 4 ไบต์ (ครั้งที่ 7 + 8) */
typedef struct {
    int16_t tempQ88;     /* ค่าที่วัดได้ เก็บแบบ Q8.8           */
    uint8_t level;       /* ระดับที่คำนวณได้                    */
    uint8_t seq;         /* ลำดับ ตั้งใจให้ล้นและวนกลับ (ครั้งที่ 3) */
} Sample;

#define LOG_SIZE 8       /* เก็บได้ 8 ตัวอย่าง แต่จะป้อนเข้าไป 12 ตัว */

